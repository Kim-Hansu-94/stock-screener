-- 저점 매집 후보 카드에 **권장 관찰 기간 배지**를 띄우기 위한 컬럼 추가. (2026-09-15)
--
-- 3년 백테스트에서 나온 결과다 — **깊게 빠진 종목은 나쁜 게 아니라 느리다.**
-- 같은 종목군인데 3개월과 1년의 승률이 정반대 방향으로 간다
-- (선발 없는 스윕 10,463건, 쏠림 큰 80%+ 구간 제외):
--
--     하락률       3개월 승률   1년 승률
--     55~60%         64.1%       74.5%
--     60~65%         63.8%       77.9%
--     65~70%         62.1%       78.8%
--     70~75%         60.3%       81.0%
--     75~80%         60.7%       81.0%
--
-- 그래서 하락률 65% 아래면 3개월, 70%를 넘으면 1년을 보고 들어가야 한다.
-- 점수는 보유 기간을 모르므로 채점으로는 풀 수 없고, 화면이 알려줘야 한다.
--
-- 하락률 값 자체는 `matched_bottom` 문자열("하락률 72% · 저점 유지 41일 · ...")
-- 안에도 있지만 **그건 사람이 읽는 표시용 문장**이다. 파싱해서 쓰면 문구를 고칠
-- 때마다 화면이 조용히 깨지므로 숫자를 따로 싣는다.
--
-- 이 파일을 실행하지 않아도 파이프라인은 죽지 않는다 — db.save_pattern_matches가
-- 실패를 감지해 기본 컬럼만으로 다시 저장하고 로그를 남긴다. 그동안 카드에는
-- 배지만 안 뜬다(목록·점수·차트는 전부 정상).
--
-- `pattern_match_results`는 매 실행 전체 삭제 후 재작성이라 **소급이 필요 없다.**
-- 실행하면 다음 파이프라인 실행부터 바로 채워진다
-- (`recommendation_history`와 결정적으로 다른 점 — 그쪽은 날짜별로 쌓이므로
--  늦게 실행할수록 과거가 영구히 빈다).

alter table pattern_match_results
  add column if not exists drawdown_pct numeric;   -- 52주 최고가 대비 하락률 (%)

