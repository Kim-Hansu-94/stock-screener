--
-- 왜 필요한가: 490590 구성이 바뀌면 사람이 증권사 앱을 캡처해 비중을 갱신해야 하는데,
-- 지금까지 알람은 **새 종목이 보일 때만** 울렸다. 반대로 담고 있던 종목이 빠지면
-- 로그에 한 줄 남을 뿐 메일도 팝업도 안 떴다(2026-09-29 사용자 지적).
--
-- 메일(워크플로 빨간불)은 이 열 없이도 동작한다. 이 열은 **사이트 팝업**에만 필요하다 —
-- etf_holdings는 매 실행 통째로 갈아끼워서 이력이 없으므로, 파이프라인이 찾아낸
-- '안 보임'을 화면에 전달할 곳이 여기밖에 없다.
--
-- 안 돌려도 화면은 안 깨진다: 파이프라인이 저장에 실패하면 보유 행만 다시 넣고
-- ::warning::을 남긴다(pipeline/src/db.py의 save_etf_holdings). 대신 **팝업이 조용히
-- 안 뜬다** — 그래서 여기 적어 둔다.
--
-- Supabase 대시보드 SQL 에디터에서 한 번 실행할 것.
